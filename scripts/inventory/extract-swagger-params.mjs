#!/usr/bin/env node
/**
 * Extract request parameters for documented AirysChat endpoints from the application
 * swagger (Chatwoot-inherited, OpenAPI 3.1) into docs/api/params.json.
 *
 *   node scripts/inventory/extract-swagger-params.mjs --swagger app_swagger.json --source <sha>
 *
 * Get the swagger without touching the AirysChat working tree:
 *   git -C ~/AirysChat show origin/develop:swagger/tag_groups/application_swagger.json > /tmp/app_swagger.json
 *
 * Only account-scoped operations (/api/v1|v2/accounts/{account_id}/…) are kept, keyed like
 * the inventory: "<METHOD> <prefix> <path with {} for params>". AirysChat-only (saas)
 * endpoints have no swagger; their params come from domain briefs (CAT-04). Path params
 * for every endpoint are derived from the route itself by build-catalog.mjs.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'docs/api/params.json');
const args = process.argv.slice(2);
const flag = (name) => {
  const index = args.indexOf(name);
  return index === -1 ? undefined : args[index + 1];
};

const swaggerPath = flag('--swagger');
if (!swaggerPath) {
  console.error('usage: extract-swagger-params.mjs --swagger <application_swagger.json> [--source <sha>]');
  process.exit(2);
}
const swagger = JSON.parse(readFileSync(swaggerPath, 'utf8'));
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
const MAX_DESCRIPTION = 160;

function resolve(node, seen = new Set()) {
  if (!node || typeof node !== 'object' || !node.$ref) return node;
  if (seen.has(node.$ref)) return {};
  seen.add(node.$ref);
  const target = node.$ref.replace(/^#\//, '').split('/').reduce((value, key) => value?.[key], swagger);
  return resolve(target, seen);
}

function typeOf(schema) {
  const resolved = resolve(schema) ?? {};
  const type = Array.isArray(resolved.type) ? resolved.type.filter((entry) => entry !== 'null')[0] : resolved.type;
  if (type === 'array') return `${typeOf(resolved.items) ?? 'unknown'}[]`;
  return type ?? (resolved.properties ? 'object' : undefined);
}

function clean(text) {
  if (!text) return undefined;
  const flat = String(text).replace(/\s+/g, ' ').trim();
  return flat.length > MAX_DESCRIPTION ? `${flat.slice(0, MAX_DESCRIPTION - 1)}…` : flat;
}

function param(name, location, schema, required, description) {
  const resolved = resolve(schema) ?? {};
  const entry = { name, in: location, required: Boolean(required) };
  const type = typeOf(resolved);
  if (type) entry.type = type;
  const values = resolved.enum ?? resolve(resolved.items)?.enum;
  if (Array.isArray(values)) entry.enum = values.filter((value) => value !== null);
  const text = clean(description ?? resolved.description);
  if (text) entry.description = text;
  return entry;
}

function bodyParams(requestBody) {
  const body = resolve(requestBody);
  const schema = resolve(body?.content?.['application/json']?.schema);
  if (!schema) return [];
  // allOf compositions are flattened one level; that covers how this swagger composes payloads.
  const parts = schema.allOf ? schema.allOf.map((part) => resolve(part)) : [schema];
  const required = new Set(parts.flatMap((part) => part?.required ?? []));
  return parts.flatMap((part) =>
    Object.entries(part?.properties ?? {}).map(([name, property]) => param(name, 'body', property, required.has(name), property?.description)),
  );
}

const operations = {};
for (const [rawPath, item] of Object.entries(swagger.paths ?? {})) {
  const match = rawPath.match(/^\/api\/(v1|v2)\/accounts\/\{account_id\}(\/.*)?$/);
  if (!match) continue;
  const prefix = match[1] === 'v2' ? 'core_v2' : 'core';
  const path = (match[2] ?? '/').replace(/\{[^}]+\}/g, '{}');
  const shared = (item.parameters ?? []).map((entry) => resolve(entry));

  for (const method of METHODS) {
    const operation = item[method];
    if (!operation) continue;
    const declared = [...shared, ...(operation.parameters ?? []).map((entry) => resolve(entry))];
    const params = declared
      .filter((entry) => entry && entry.name !== 'account_id' && ['path', 'query'].includes(entry.in))
      .map((entry) => param(entry.name, entry.in, entry.schema, entry.required || entry.in === 'path', entry.description))
      .concat(bodyParams(operation.requestBody));
    operations[`${method.toUpperCase()} ${prefix} ${path}`] = {
      summary: clean(operation.summary ?? operation.description),
      params,
    };
  }
}

const sorted = Object.fromEntries(Object.entries(operations).sort(([a], [b]) => a.localeCompare(b)));
const output = {
  $comment:
    'Generated by scripts/inventory/extract-swagger-params.mjs from AirysChat swagger/tag_groups/application_swagger.json. ' +
    'Do not edit by hand; regenerate with the sync-api-inventory skill.',
  source: flag('--source') ?? 'unknown',
  operations: sorted,
};
writeFileSync(OUT, `${JSON.stringify(output, null, 2)}\n`);
console.log(`params.json: ${Object.keys(sorted).length} documented operations`);
