#!/usr/bin/env node
/**
 * Build the endpoint catalog shipped inside @airyschat/mcp (CAT-05).
 *
 *   node scripts/inventory/build-catalog.mjs [--out packages/server/catalog.json] [--stats]
 *
 * Inputs (all committed, no AirysChat checkout needed):
 *   docs/api/inventory.csv            every account-scoped route, toolset, coverage
 *   docs/api/params.json              swagger-documented params (CAT-03)
 *   scripts/inventory/irreversible.json  irreversible classification (CAT-08)
 *
 * The catalog powers `airyschat_api_search` (CAT-06) and the validation and gates of
 * `airyschat_api` (CAT-07). It is generated at build time and git-ignored, so it can
 * never drift from the inventory. No tenant data: method, path, controller, params.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const args = process.argv.slice(2);
const outIndex = args.indexOf('--out');
const OUT = outIndex === -1 ? join(ROOT, 'packages/server/catalog.json') : args[outIndex + 1];

const inventory = parseCsv(readFileSync(join(ROOT, 'docs/api/inventory.csv'), 'utf8'));
const { operations } = JSON.parse(readFileSync(join(ROOT, 'docs/api/params.json'), 'utf8'));
const { rules } = JSON.parse(readFileSync(join(ROOT, 'scripts/inventory/irreversible.json'), 'utf8'));
const compiled = rules.map((rule) => ({ method: new RegExp(`^(${rule.method})$`), path: new RegExp(rule.path), reason: rule.reason }));

const irreversibleReason = (method, path) => compiled.find((rule) => rule.method.test(method) && rule.path.test(path))?.reason;

const endpoints = [];
for (const row of inventory) {
  if (row.coverage === 'removed') continue;
  const key = `${row.method} ${row.prefix} ${row.path.replace(/:[a-z_]+/g, '{}')}`;
  const documented = operations[key];
  const pathParams = [...row.path.matchAll(/:([a-z_]+)/g)].map(([, name]) => ({ name, in: 'path', required: true }));
  // Swagger names path params differently at times (id vs conversation_id); the route wins.
  const otherParams = (documented?.params ?? []).filter((param) => param.in !== 'path');
  const write = row.method !== 'GET';
  const reason = write ? irreversibleReason(row.method, row.path) : undefined;

  const entry = {
    method: row.method,
    prefix: row.prefix,
    path: row.path,
    domain: row.domain,
    toolset: row.toolset,
    action: row.controller.replace(/^.*\/accounts\//, '').replace(/^saas\/api\/v1\//, ''),
    coverage: row.coverage,
  };
  if (row.tool) entry.tool = row.tool;
  if (documented?.summary) entry.summary = documented.summary;
  const params = [...pathParams, ...otherParams];
  if (params.length) entry.params = params;
  if (write) entry.write = true;
  if (reason) entry.irreversible = reason;
  if (row.coverage === 'excluded') entry.excluded = row.notes || 'Not drivable through MCP';
  endpoints.push(entry);
}

const catalog = {
  $comment: 'Generated by scripts/inventory/build-catalog.mjs at build time. Do not edit.',
  source: JSON.parse(readFileSync(join(ROOT, 'docs/api/inventory.meta.json'), 'utf8')).source ?? 'unknown',
  endpoints,
};
const text = JSON.stringify(catalog);
writeFileSync(OUT, text);

if (args.includes('--stats')) {
  const count = (predicate) => endpoints.filter(predicate).length;
  console.log(
    `catalog: ${endpoints.length} endpoints, ${count((e) => e.write)} writes, ${count((e) => e.irreversible)} irreversible, ` +
      `${count((e) => e.excluded)} excluded, ${count((e) => e.summary)} documented, ${(text.length / 1024).toFixed(0)} KB`,
  );
}

function parseCsv(source) {
  const lines = [];
  let field = '';
  let record = [];
  let quoted = false;
  for (let i = 0; i < source.length; i++) {
    const char = source[i];
    if (quoted) {
      if (char === '"' && source[i + 1] === '"') { field += '"'; i++; }
      else if (char === '"') quoted = false;
      else field += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') { record.push(field); field = ''; }
    else if (char === '\n') { record.push(field); lines.push(record); record = []; field = ''; }
    else if (char !== '\r') field += char;
  }
  if (field || record.length) { record.push(field); lines.push(record); }
  const [header, ...body] = lines;
  return body.filter((r) => r.length > 1).map((r) => Object.fromEntries(header.map((column, index) => [column, r[index] ?? ''])));
}
